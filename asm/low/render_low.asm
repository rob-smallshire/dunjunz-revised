;
; load_creature for monster X: its sprite (0 if nothing is on show) in sprite_number, its
; cell in cell_x and cell_y, its offsets in plot_offset_x and plot_offset_y.
.load_monster_look
    stx render_creature                 ; Creature = 46 - monster
    lda #46                             ; ...
    sec                                 ; ...
    sbc render_creature                 ; ...
    tax                                 ; ...
    jsr load_creature                   ; ...
    bcc monster_loaded                  ; On show: as loaded
    lda #0                              ; Nothing: sprite 0
    sta sprite_number                   ; ...
.monster_loaded
    rts                                 ; Return
; Plot sprite_number squarely in cell_x, cell_y, solid (A = 0) or see-through (A = &80),
; leaving cell_x and cell_y as they were. Corrupts X and Y.
.plot_floor
    sta plot_mode                       ; Solid or see-through
    lda cell_x                          ; Keep the cell...
    pha                                 ; ...
    lda cell_y                          ; ...
    pha                                 ; ...
    lda #0                              ; ...squarely in it
    sta plot_offset_x                   ; ...
    sta plot_offset_y                   ; ...
    jsr plot_at_cell                    ; Plot it in every view showing the cell
    pla                                 ; Recover the cell
    sta cell_y                          ; ...
    pla                                 ; ...
    sta cell_x                          ; ...
    lda #0                              ; Solid again
    sta plot_mode                       ; ...
    rts                                 ; Return
