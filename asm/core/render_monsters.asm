; Note a monster as it looks, and mark it if it changes
;
; update_monsters calls note_monster for monster X before moving it, and
; mark_monster_if_changed when it is done, so a
; monster that looks as it did, the same sprite in the same place, marks nothing and is
; not drawn again, and one that changed has the cells it covered and covers marked
; (mark_cells). The note is the monster as load_creature gives it (monster_before): its
; sprite, 0 for nothing on show, cell and offsets. In the 1987 release every monster was
; rubbed out and plotted again every frame.
.note_monster
    stx render_view                     ; Keep the monster
    jsr load_monster_look               ; As it looks now...
    lda sprite_number                   ; ...noted: sprite...
    sta monster_before                  ; ...
    lda cell_x                          ; ...cell...
    sta monster_before + 1              ; ...
    lda cell_y                          ; ...
    sta monster_before + 2              ; ...
    lda plot_offset_x                   ; ...and offsets
    sta monster_before + 3              ; ...
    lda plot_offset_y                   ; ...
    sta monster_before + 4              ; ...
    ldx render_view                     ; Recover the monster
    rts                                 ; Return
; Monster X has been moved: mark its cells if it looks different. Corrupts X.
.mark_monster_if_changed
    jsr load_monster_look               ; As it looks now: the same as before?
    lda sprite_number                   ; ...sprite...
    cmp monster_before                  ; ...
    bne monster_changed                 ; ...
    lda cell_x                          ; ...cell...
    cmp monster_before + 1              ; ...
    bne monster_changed                 ; ...
    lda cell_y                          ; ...
    cmp monster_before + 2              ; ...
    bne monster_changed                 ; ...
    lda plot_offset_x                   ; ...offsets
    cmp monster_before + 3              ; ...
    bne monster_changed                 ; ...
    lda plot_offset_y                   ; ...
    cmp monster_before + 4              ; ...
    bne monster_changed                 ; ...
    rts                                 ; Yes: nothing to draw afresh
.monster_changed
    lda sprite_number                   ; Changed. On show now?
    beq mark_monster_before             ; No: just where it was
    jsr mark_cells                      ; Yes: mark where it is
.mark_monster_before
    lda monster_before                  ; On show before?
    beq monster_marked                  ; No: done
    lda monster_before + 1              ; Yes: mark where it was
    sta cell_x                          ; ...
    lda monster_before + 2              ; ...
    sta cell_y                          ; ...
    lda monster_before + 3              ; ...
    sta plot_offset_x                   ; ...
    lda monster_before + 4              ; ...
    sta plot_offset_y                   ; ...
    jmp mark_cells                      ; ...and return
.monster_marked
    rts                                 ; Return
